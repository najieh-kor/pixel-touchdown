const CACHE = 'pixel-touchdown-' + CACHE_VERSION;
const PREFIX = 'pixel-touchdown-';

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // all-or-nothing: a failed file fails the install and the previous version keeps serving.
    // 'reload' skips the HTTP cache so a new version never precaches stale copies.
    await Promise.all(PRECACHE.map(async (u) => {
      const r = await fetch(new Request(u, { cache: 'reload' }));
      if (!r.ok) throw new Error('precache ' + u + ': HTTP ' + r.status);
      await cache.put(u, await clean(r));
    }));
    // the bare scope URL ("./") may not map to index.html on every host: cache it best-effort
    try {
      const r = await fetch(new Request('./', { cache: 'reload' }));
      if (r && r.ok) await cache.put('./', await clean(r));
    } catch (e) { /* ignore */ }
    await self.skipWaiting();
  })());
});

/** A redirected response cannot answer a navigation (Safari/Chrome reject it): copy it into a plain one. */
async function clean(res) {
  if (!res.redirected) return res;
  return new Response(await res.blob(), { status: res.status, statusText: res.statusText, headers: res.headers });
}

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    const old = keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE);
    await Promise.all(old.map((k) => caches.delete(k)));
    await self.clients.claim();
    if (old.length) {
      const list = await self.clients.matchAll({ type: 'window' });
      list.forEach((c) => c.postMessage({ type: 'pt-sw-updated', version: CACHE_VERSION }));
    }
  })());
});

self.addEventListener('message', (event) => {
  const d = event.data || {};
  if (d.type === 'pt-sw-version' && event.source) event.source.postMessage({ type: 'pt-sw-version', version: CACHE_VERSION });
});

/** Fetch from the network and store a good same-origin copy in the current cache. */
async function refresh(request, key) {
  const res = await fetch(request);
  if (res && res.ok && res.type === 'basic') {
    const cache = await caches.open(CACHE);
    await cache.put(key || request, await clean(res.clone()));
  }
  return res;
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  const nav = req.mode === 'navigate';

  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // query strings (?test=1, ?seed=…) never change the file served
    // network-first: always load the newest build when the server is reachable (no stale mixes after a release);
    // the cache is only the offline fallback. A slow network falls back to cache after 3 s.
    try {
      return await Promise.race([
        refresh(req, nav ? stripSearch(url) : null),
        new Promise((_, rej) => setTimeout(() => rej(new Error('slow')), 3000))
      ]);
    } catch (e) {
      let hit = await cache.match(req, { ignoreSearch: true });
      if (!hit && nav) hit = (await cache.match('./index.html')) || (await cache.match('./'));
      if (hit) return hit;
      if (nav) {
        const fallback = await cache.match('./index.html');
        if (fallback) return fallback;
      }
      return new Response('Offline', { status: 503, statusText: 'Offline' });
    }
  })());
});

/** Cache key for a navigation: the URL without its query string. */
function stripSearch(url) {
  return url.origin + url.pathname;
}
